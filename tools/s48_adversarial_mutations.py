"""Create isolated S48 shadow sources; never edit the production checkout.

Run from the repository: python tools/s48_adversarial_mutations.py OUTPUT.
Pass the selected output directory and original source to the public init script
with s48ShadowDir and s48ShadowOriginal. RED means the matching oracle kills it.
"""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PACKAGE = Path('io/github/r3neer/scalebrews/collision/internal')


def replace_once(source, old, new):
    if source.count(old) != 1:
        raise ValueError(f'Expected one mutation anchor: {old!r}')
    return source.replace(old, new)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('output', type=Path)
    args = parser.parse_args()
    sources = {name: (ROOT / 'src/main/java' / PACKAGE / (name + '.java')).read_text(encoding='utf-8')
               for name in ('AnatomyRuntime', 'AnatomyMovement', 'PreparedVariantBindings')}
    runtime = sources['AnatomyRuntime']
    movement = sources['AnatomyMovement']
    prepared = sources['PreparedVariantBindings']
    recipes = {
        'clock-reset': ('AnatomyRuntime', replace_once(runtime,
            'selected::supportsAuthorityPose,participant.clock',
            'selected::supportsAuthorityPose,new AuthorityPoseTracker()')),
    }
    # The remaining historical shadow files are generated by this same checked
    # contract; anchors below deliberately fail if production changes shape.
    import re
    generation = re.search(r'long bindingGeneration\s*=\s*[^;]+;', runtime)
    if generation is None:
        raise ValueError('Missing physical-generation allocation')
    recipes['generation-reuse'] = ('AnatomyRuntime', replace_once(runtime,
        generation.group(0), 'long bindingGeneration=1L;'))
    withdrawal = re.search(r'AnatomyNetworking\.sendPose\(recipient,\s*withdrawal,\s*tracking\);', runtime)
    if withdrawal is None:
        raise ValueError('Missing exact withdrawal publication')
    recipes['withdrawal-omitted'] = ('AnatomyRuntime', replace_once(runtime,
        withdrawal.group(0), '/* test-only omitted withdrawal */;'))
    guard = re.search(r'provider!=AnatomyBindingState\.provider\(support\)', movement)
    if guard is None:
        raise ValueError('Missing registered-provider fence')
    recipes['stale-provider'] = ('AnatomyMovement', replace_once(movement,
        guard.group(0), 'false /* test-only omitted registered-owner fence */'))
    # Only the SOURCE_UNAVAILABLE branch: read still returns null, while the
    # observation getter erroneously keeps A. This distinguishes two consumers.
    failure = re.search(r'(known\s*=\s*false;\s*)selected\s*=\s*null;', prepared)
    if failure is None:
        raise ValueError('Missing unknown-source selection retirement')
    recipes['stale-policy'] = ('PreparedVariantBindings', replace_once(prepared,
        failure.group(0), failure.group(1) + '/* test-only stale selected row */'))
    instrument = replace_once(prepared, '    static final int MAX_AXES = 32;',
        '    static final int MAX_AXES = 32;\n'
        '    static final java.util.concurrent.atomic.AtomicLong ADV_RESOLVES=new java.util.concurrent.atomic.AtomicLong();\n'
        '    private static java.util.Optional<WorldAnatomyCatalog.Binding> resolve(Plan plan,Map<String,String> inputs){ADV_RESOLVES.incrementAndGet();return plan.snapshot().resolve(plan.type(),inputs);}')
    instrument = replace_once(instrument, 'plan.snapshot().resolve(plan.type(), Map.of())', 'resolve(plan, Map.of())')
    instrument = replace_once(instrument, 'plan.snapshot().resolve(plan.type(), Collections.unmodifiableMap(values))', 'resolve(plan, Collections.unmodifiableMap(values))')
    recipes['instrument'] = ('PreparedVariantBindings', instrument)
    receipt = {}
    for kind, (owner, content) in recipes.items():
        path = args.output / kind / PACKAGE / (owner + '.java')
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding='utf-8', newline='\n')
        receipt[kind] = {'owner': 'src/main/java/' + str(PACKAGE / (owner + '.java')).replace('\\', '/'),
                         'sourceSha256': hashlib.sha256((ROOT / 'src/main/java' / PACKAGE / (owner + '.java')).read_bytes()).hexdigest(),
                         'shadowSha256': hashlib.sha256(content.encode()).hexdigest()}
    (args.output / 'mutations.json').write_text(json.dumps(receipt, indent=2) + '\n', encoding='utf-8')
    print(json.dumps(receipt, indent=2))


if __name__ == '__main__':
    main()
